"""Disposable loopback server only. ViaCEP is mocked: no real customer data or external lookup."""
import json
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1280,'height':900});errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 pending=[]
 def postal_route(route):
  if '99999999' in route.request.url:route.fulfill(json={'erro':True},headers={'access-control-allow-origin':'*'})
  elif '88888888' in route.request.url:route.abort()
  else:pending.append(route)
 page.route('https://viacep.com.br/**',postal_route)
 page.goto('http://127.0.0.1:8196/?view=clientes')
 page.get_by_role('button',name='Novo cliente',exact=True).click()
 modal=page.get_by_role('dialog')
 modal.get_by_role('button',name='Salvar cliente',exact=True).click()
 expect(modal.get_by_role('alert')).to_contain_text('nome da empresa ou o nome do contato')
 modal.get_by_label('Nome do contato',exact=True).fill('Pessoa fictícia sem empresa')
 modal.get_by_label('CEP de entrega',exact=True).fill('12345-678')
 modal.get_by_label('Número',exact=True).fill('12 A')
 modal.get_by_label('Complemento',exact=True).fill('Sala de teste')
 with page.expect_request('https://viacep.com.br/**'):
  modal.get_by_role('button',name='Buscar endereço pelo CEP',exact=True).click()
 expect(modal.get_by_role('button',name='Salvar cliente',exact=True)).to_be_disabled()
 modal.get_by_label('Rua / logradouro',exact=True).fill('Rua digitada manualmente')
 pending.pop().fulfill(json={'cep':'12345-678','logradouro':'Rua retornada','bairro':'Bairro de teste','localidade':'Cidade de teste','uf':'SP'},headers={'access-control-allow-origin':'*'})
 expect(modal.get_by_label('Cidade',exact=True)).to_have_value('Cidade de teste')
 expect(modal.get_by_label('Rua / logradouro',exact=True)).to_have_value('Rua digitada manualmente')
 expect(modal.get_by_label('Número',exact=True)).to_have_value('12 A')
 expect(modal.get_by_label('Complemento',exact=True)).to_have_value('Sala de teste')
 modal.get_by_role('button',name='Salvar cliente',exact=True).click()
 page.get_by_role('heading',name='Pessoa fictícia sem empresa',exact=True).wait_for()
 page.reload()
 page.locator('.client-record').filter(has=page.get_by_role('heading',name='Pessoa fictícia sem empresa',exact=True)).get_by_role('button',name='Editar',exact=True).click()
 modal=page.get_by_role('dialog')
 expect(modal.get_by_label('Nome da empresa',exact=True)).to_have_value('')
 expect(modal.get_by_label('Cidade',exact=True)).to_have_value('Cidade de teste')
 modal.get_by_label('CEP de entrega',exact=True).fill('99999-999')
 modal.get_by_role('button',name='Buscar endereço pelo CEP',exact=True).click()
 expect(modal.get_by_role('status')).to_contain_text('CEP não encontrado')
 modal.get_by_label('CEP de entrega',exact=True).fill('88888-888')
 modal.get_by_role('button',name='Buscar endereço pelo CEP',exact=True).click()
 expect(modal.get_by_role('status')).to_contain_text('preenchimento manual continua disponível')
 modal.get_by_label('Cidade',exact=True).fill('Cidade manual')
 modal.get_by_role('button',name='Salvar cliente',exact=True).click()
 page.get_by_role('navigation',name='Áreas').get_by_role('link',name='Orçamentos',exact=True).click()
 page.get_by_role('button',name='Novo orçamento',exact=True).click()
 page.get_by_label('Selecionar cliente',exact=True).select_option(label='Pessoa fictícia sem empresa')
 page.get_by_text('Ver dados do cliente',exact=True).click()
 expect(page.locator('.wf-client-details')).to_contain_text('Cidade manual')
 page.get_by_role('button',name='Salvar rascunho',exact=True).first.click()
 page.get_by_role('status').filter(has_text='Rascunho salvo.').wait_for()
 page.reload()
 page.locator('.quote-record[data-record-id="1"]').get_by_role('button',name='Editar',exact=True).click()
 page.get_by_role('button',name='Editar cadastro do cliente',exact=True).click()
 modal=page.get_by_role('dialog')
 expect(modal.get_by_label('Nome do contato',exact=True)).to_have_value('Pessoa fictícia sem empresa')
 expect(modal.get_by_label('Cidade',exact=True)).to_have_value('Cidade manual')
 expect(modal.get_by_label('Número',exact=True)).to_have_value('12 A')
 # Contact alone must also work inside the quote modal.
 modal.get_by_role('button',name='Salvar cadastro do cliente',exact=True).click()
 page.get_by_text('Cliente salvo no cadastro e selecionado neste orçamento.',exact=True).wait_for()
 page.set_viewport_size({'width':390,'height':844})
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 assert not errors,errors
 browser.close()
print('Contato sem empresa, endereço persistente, consulta por CEP simulada, falhas e preservação de edição manual: OK.')
